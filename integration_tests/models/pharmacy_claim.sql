-- Preserve the published Tuva synthetic claims; append the independent scenarios.
select
    claim_id,
    claim_line_number,
    person_id,
    member_id,
    payer,
    {{ the_tuva_project.quote_column('plan') }},
    prescribing_provider_npi,
    dispensing_provider_npi,
    dispensing_date,
    ndc_code,
    quantity,
    days_supply,
    refills,
    paid_date,
    paid_amount,
    allowed_amount,
    charge_amount,
    coinsurance_amount,
    copayment_amount,
    deductible_amount,
    in_network_flag,
    data_source,
    file_name,
    file_date,
    ingest_datetime
from {{ ref('the_tuva_project', 'synthetic_data__pharmacy_claim') }}
union all
select
    cast(s.claim_id as {{ dbt.type_string() }}) as claim_id,
    cast(1 as {{ dbt.type_int() }}) as claim_line_number,
    cast(s.person_id as {{ dbt.type_string() }}) as person_id,
    cast(s.person_id as {{ dbt.type_string() }}) as member_id,
    cast('Scenario Payer' as {{ dbt.type_string() }}) as payer,
    cast('Scenario Plan' as {{ dbt.type_string() }}) as {{ the_tuva_project.quote_column('plan') }},
    cast(null as {{ dbt.type_string() }}) as prescribing_provider_npi,
    cast(null as {{ dbt.type_string() }}) as dispensing_provider_npi,
    cast(s.dispensing_date as date) as dispensing_date,
    cast(p.ndc_code as {{ dbt.type_string() }}) as ndc_code,
    cast(s.quantity as {{ dbt.type_int() }}) as quantity,
    cast(s.days_supply as {{ dbt.type_int() }}) as days_supply,
    cast(0 as {{ dbt.type_int() }}) as refills,
    cast(s.dispensing_date as date) as paid_date,
    cast(s.paid_amount as {{ dbt.type_numeric() }}) as paid_amount,
    cast(null as {{ dbt.type_numeric() }}) as allowed_amount,
    cast(null as {{ dbt.type_numeric() }}) as charge_amount,
    cast(null as {{ dbt.type_numeric() }}) as coinsurance_amount,
    cast(null as {{ dbt.type_numeric() }}) as copayment_amount,
    cast(null as {{ dbt.type_numeric() }}) as deductible_amount,
    cast(1 as {{ dbt.type_int() }}) as in_network_flag,
    cast(s.data_source as {{ dbt.type_string() }}) as data_source,
    cast('drugs_controlled_scenarios_20261110.csv' as {{ dbt.type_string() }}) as file_name,
    cast('2026-11-10' as date) as file_date,
    cast('2026-11-10 08:00:00' as {{ dbt.type_timestamp() }}) as ingest_datetime
from {{ ref('scenario_pharmacy_claims') }} s join {{ ref('scenario_products') }} p on s.drug_key=p.drug_key
